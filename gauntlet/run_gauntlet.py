#!/usr/bin/env python3
"""B6+ — the multi-turn gauntlet runner.

Runs the scripted 8-turn conversation (scenario.json) against two arms
with the SAME model, the SAME base system prompt, and the SAME product
tools (get_order_status, issue_refund, loaded from v0/agent.py so the
contracts are the folders' own):

  Arm A — transcript only: the conversation is the only state.
  Arm B — transcript + a persisted, versioned case file (casefile.py):
          the agent also gets read_case_file / update_case_file. That
          difference IS the treatment; everything else is held equal.

Between turns 5 and 6 the gauntlet FORCES the two events the bite is
about (reality-raising rule — forced, not narrated):
  * compaction: the transcript is replaced by a short model-written
    prose summary (generated by the driver, saved verbatim), and
  * a real process restart: each phase runs as its own OS process
    (`phase` mode), so phase 2 can only know what reached disk —
    the summary for both arms, plus the case file for Arm B.

Store discipline: the driver (`all` mode) snapshots the seeded base
store, restores it before each arm, snapshots each arm's store after
each phase into the arm's run folder, and restores the base at the end
(the test-suite's snapshot/restore discipline, for the same reason:
parallel universes must not leak into the live store's real history —
each arm's artifacts live in its run folder instead).

Usage:
    python3 run_gauntlet.py all                 # both arms + scorecard
    python3 run_gauntlet.py phase --arm B --phase 1   # one phase only
"""

import argparse
import importlib.util
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
RUNS = HERE / "runs"
STORE = ROOT / "tools" / "store.json"
SCENARIO = json.loads((HERE / "scenario.json").read_text(encoding="utf-8"))

sys.path.insert(0, str(HERE))
import casefile

# Reuse v0's model call and product tools — same contracts, same code.
_spec = importlib.util.spec_from_file_location("sd_agent", ROOT / "v0" / "agent.py")
agent = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(agent)

BASE_PROMPT = """You are the agent for Support Desk, handling ONE customer's case across a multi-turn conversation. Each user message is the customer's latest message. Reply to the latest message and keep the case moving.

Rules:
- Never invent facts. Order facts may only come from the get_order_status tool.
- Refunds: use issue_refund, and always call it with preview=true first. If the refund is right, call it again with preview=false - that SUBMITS it to the approval gate; it does not issue it. Never tell the customer a refund has been issued or completed. Say it has been submitted and is awaiting human approval.
- Never submit a refund for the same order twice. If a refund for an order is already submitted and awaiting approval, say so instead of submitting again.
- If the customer's target is ambiguous - more than one order is in play and it is not clear which one they mean - ask which order they mean and take NO write action (no refund calls) on that turn.
- Keep each reply short: a few sentences, no drafts, no essays."""

CASEFILE_PROMPT = """

You also keep a CASE FILE: your versioned working state, kept outside this conversation (schema: case_id, state_version, customer_ref, current_goal, current_order_id, live_order_ids, facts [{fact, source, order_id}], latest_decision {remedy, order_id, decided_turn}, superseded_decisions [{remedy, order_id, status, superseded_by_turn}], completed_actions [{action_id, kind, order_id, amount, receipt_readback}], pending_approval {action_id, order_id, amount, status} or null, open_question, updated_at_turn).
- Call read_case_file at the start of your first turn, and again whenever the session resumes after a pause.
- BEFORE acting on any turn that changes the case - a new goal, an order switch, a changed or reversed decision, a completed action, a pending approval - call update_case_file with the COMPLETE updated file. When a decision is replaced, move the old one into superseded_decisions, labeled superseded - never delete it. Record completed actions only from tool results. Exact order ids, amounts, and action ids live in the case file, never only in your reply text."""

CASE_TOOLS = [
    {
        "name": "read_case_file",
        "description": "Read this case's case file: the versioned working state kept outside the conversation (current goal and order, facts with sources, latest and superseded decisions, completed actions, pending approval, open question). Returns the file as JSON, or a note that no case file exists yet.",
        "input_schema": {"type": "object", "properties": {}},
    },
    {
        "name": "update_case_file",
        "description": "Save an accepted update to the case file. Pass the COMPLETE file (every field), not a diff. The harness increments state_version and stamps the turn; superseded decisions you omit are restored from the previous file, never lost.",
        "input_schema": {
            "type": "object",
            "properties": {"case_file": {"type": "object"}},
            "required": ["case_file"],
        },
    },
]

MAX_STEPS_PER_TURN = 5


def store_counts():
    s = json.loads(STORE.read_text(encoding="utf-8"))
    return {
        "pending": len(s.get("pending_actions", [])),
        "refunds": len(s.get("refunds", [])),
        "drafts": len(s.get("drafts", [])),
    }


def run_phase(arm, phase):
    arm_dir = RUNS / f"arm_{arm.lower()}"
    arm_dir.mkdir(parents=True, exist_ok=True)
    trace_path = arm_dir / "trace.txt"
    turns_path = arm_dir / "turns.json"
    case_path = arm_dir / "casefile.json"
    turns_log = json.loads(turns_path.read_text(encoding="utf-8")) if turns_path.exists() else {}

    tools = [agent.CONTRACT_BY_NAME[n] for n in ("get_order_status", "issue_refund")]
    system = BASE_PROMPT
    if arm == "B":
        tools = tools + CASE_TOOLS
        system = BASE_PROMPT + CASEFILE_PROMPT

    messages = []
    if phase == 2:
        summary = (arm_dir / "summary.txt").read_text(encoding="utf-8").strip()
        turns = [t for t in SCENARIO["turns"] if t["phase"] == 2]
        first = turns[0]
        resume = (
            "(The session was restarted and the earlier conversation was compacted. "
            f"Summary of the conversation so far:\n{summary})\n\n"
            + (("Your case file was saved before the restart and is still on disk. "
                "Call read_case_file before acting.\n\n") if arm == "B" else "")
            + f"Customer: {first['customer']}"
        )
        messages.append({"role": "user", "content": resume})
        turn_plan = [(first, True)] + [(t, False) for t in turns[1:]]
    else:
        turns = [t for t in SCENARIO["turns"] if t["phase"] == 1]
        turn_plan = [(t, False) for t in turns]

    trace = open(trace_path, "a", encoding="utf-8")

    def log(line=""):
        trace.write(line + "\n")
        trace.flush()
        print(line)

    log(f"\n===== ARM {arm} · PHASE {phase} (process {__import__('os').getpid()}) =====")
    total_in = total_out = 0

    for turn, is_resume in turn_plan:
        n = turn["n"]
        if not is_resume:
            messages.append({"role": "user", "content": f"Customer: {turn['customer']}"})
        log(f"\n--- TURN {n} · customer: {turn['customer']}")
        call_counts = {}
        reply_text = ""
        for step in range(1, MAX_STEPS_PER_TURN + 1):
            reply = agent.call_model(messages, system=system, tools=tools)
            i, o = agent.tokens_of(reply)
            total_in += i
            total_out += o
            messages.append({"role": "assistant", "content": reply["content"]})
            tool_uses = [b for b in reply["content"] if b.get("type") == "tool_use"]
            texts = [b.get("text", "") for b in reply["content"] if b.get("type") == "text"]
            if texts:
                reply_text = "\n".join(texts).strip()
            if not tool_uses:
                break
            results = []
            stop_turn = False
            for tu in tool_uses:
                name, args = tu["name"], tu.get("input", {})
                key = f"{name}:{json.dumps(args, sort_keys=True)}"
                call_counts[key] = call_counts.get(key, 0) + 1
                if call_counts[key] >= 3:
                    result = ("Loop brake: this exact call has already run twice this turn. "
                              "Do not repeat it; answer with what you have.")
                    stop_turn = True
                elif name in agent.TOOL_FUNCS:
                    result = agent.TOOL_FUNCS[name](**args)
                elif arm == "B" and name == "read_case_file":
                    current = casefile.load(case_path)
                    result = json.dumps(current) if current else (
                        "No case file exists yet for this case. Create one with "
                        "update_case_file before acting on a change.")
                elif arm == "B" and name == "update_case_file":
                    written = casefile.accept_update(case_path, args.get("case_file", {}), n)
                    result = (f"Case file saved: state_version is now {written['state_version']}, "
                              f"updated_at_turn {n}.")
                else:
                    result = f"Unknown tool: {name}"
                log(f"  TOOL {name} {json.dumps(args)[:220]} -> {str(result)[:400]}")
                results.append({"type": "tool_result", "tool_use_id": tu["id"], "content": str(result)})
            messages.append({"role": "user", "content": results})
            if stop_turn:
                log("  BRAKE: repeated-call rule stopped this turn's tool loop.")
                break
        counts = store_counts()
        log(f"  REPLY: {reply_text}")
        log(f"  STORE AFTER TURN: {counts}")
        turns_log[str(n)] = {"reply": reply_text, **counts}
        turns_path.write_text(json.dumps(turns_log, indent=2) + "\n", encoding="utf-8")

    cost = (total_in * agent.INPUT_USD_PER_MTOK + total_out * agent.OUTPUT_USD_PER_MTOK) / 1_000_000
    log(f"\nARM {arm} PHASE {phase} TOKENS: {total_in} in / {total_out} out, est. ${cost:.4f}")
    totals_path = arm_dir / "totals.json"
    totals = json.loads(totals_path.read_text(encoding="utf-8")) if totals_path.exists() else {"in": 0, "out": 0}
    totals["in"] += total_in
    totals["out"] += total_out
    totals_path.write_text(json.dumps(totals, indent=2) + "\n", encoding="utf-8")
    trace.close()


def make_summary(arm):
    """Force compaction: a model-written prose summary replaces the
    transcript. This is the lossy artifact the bite warns about — kept
    verbatim in the arm's run folder so the scorecard can be audited."""
    arm_dir = RUNS / f"arm_{arm.lower()}"
    turns_log = json.loads((arm_dir / "turns.json").read_text(encoding="utf-8"))
    lines = []
    for t in SCENARIO["turns"]:
        if t["phase"] == 1:
            lines.append(f"Customer: {t['customer']}")
            lines.append(f"Agent: {turns_log[str(t['n'])]['reply']}")
    reply = agent.call_model(
        [{"role": "user", "content": "Summarize this support conversation in under 120 words of prose, "
                                     "as a handover note for the next agent:\n\n" + "\n".join(lines)}],
        system="You write short handover summaries of support conversations.",
        tools=None,
    )
    text = "".join(b.get("text", "") for b in reply["content"] if b.get("type") == "text").strip()
    (arm_dir / "summary.txt").write_text(text + "\n", encoding="utf-8")
    return text


def score_arm(arm, base):
    arm_dir = RUNS / f"arm_{arm.lower()}"
    final = json.loads((arm_dir / "store_final.json").read_text(encoding="utf-8"))
    turns_log = json.loads((arm_dir / "turns.json").read_text(encoding="utf-8"))
    after_p1 = json.loads((arm_dir / "store_after_phase1.json").read_text(encoding="utf-8"))
    prices = {oid: o["price"] for oid, o in SCENARIO["orders"].items()}

    pend = final.get("pending_actions", [])
    pend_3101 = [a for a in pend if a["order_id"] == "ORD-3101"]
    base_pend_ids = {a["action_id"] for a in base.get("pending_actions", [])}
    new_pend = [a for a in pend if a["action_id"] not in base_pend_ids]
    duplicates = max(0, len(pend_3101) - 1) + sum(
        max(0, len([a for a in new_pend if a["order_id"] == oid]) - 1) for oid in prices if oid != "ORD-3101"
    )
    executed = len(final.get("refunds", [])) - len(base.get("refunds", []))
    wrong_order = [
        a["action_id"] for a in new_pend
        if a["order_id"] not in prices or abs(a["amount"] - prices[a["order_id"]]) > 0.001
    ]
    turn4 = turns_log.get("4", {})
    turn3 = turns_log.get("3", {})
    turn4_wrote = any(turn4.get(k, 0) != turn3.get(k, 0) for k in ("pending", "refunds", "drafts"))

    p1_pend_3101 = [a for a in after_p1.get("pending_actions", []) if a["order_id"] == "ORD-3101"]
    expected_id = p1_pend_3101[-1]["action_id"] if p1_pend_3101 else None
    reply6 = turns_log.get("6", {}).get("reply", "")
    resume_exact = bool(expected_id) and expected_id in reply6 and "49.99" in reply6
    reply8 = turns_log.get("8", {}).get("reply", "")
    final_status_ok = bool(expected_id) and expected_id in reply8 and (
        "awaiting approval" in reply8.lower() or "pending" in reply8.lower()
    ) and "has been issued" not in reply8.lower() and "was issued" not in reply8.lower()

    totals = json.loads((arm_dir / "totals.json").read_text(encoding="utf-8"))
    return {
        "arm": arm,
        "new_pending_actions": [a["action_id"] for a in new_pend],
        "duplicate_writes": duplicates,
        "executed_refunds (skipped gates)": executed,
        "wrong_order_actions": wrong_order,
        "turn4_store_write (ambiguity)": turn4_wrote,
        "expected_pending_id_after_phase1": expected_id,
        "resume_exact (turn 6 names id + $49.99)": resume_exact,
        "final_status_names_pending (turn 8)": final_status_ok,
        "tokens_total": totals["in"] + totals["out"],
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("mode", choices=["all", "phase"])
    parser.add_argument("--arm", choices=["A", "B"])
    parser.add_argument("--phase", type=int, choices=[1, 2])
    args = parser.parse_args()

    if args.mode == "phase":
        run_phase(args.arm, args.phase)
        return

    base = json.loads(STORE.read_text(encoding="utf-8"))
    (RUNS / "base_store.json").write_text(json.dumps(base, indent=2) + "\n", encoding="utf-8")
    results = []
    try:
        for arm in ("A", "B"):
            arm_dir = RUNS / f"arm_{arm.lower()}"
            arm_dir.mkdir(parents=True, exist_ok=True)
            for stale in ("trace.txt", "turns.json", "totals.json", "casefile.json", "summary.txt"):
                p = arm_dir / stale
                if p.exists():
                    p.unlink()
            STORE.write_text(json.dumps(base, indent=2) + "\n", encoding="utf-8")
            subprocess.run([sys.executable, str(HERE / "run_gauntlet.py"), "phase",
                            "--arm", arm, "--phase", "1"], check=True, cwd=str(ROOT))
            (arm_dir / "store_after_phase1.json").write_text(STORE.read_text(encoding="utf-8"), encoding="utf-8")
            summary = make_summary(arm)
            print(f"\n### ARM {arm} · COMPACTION SUMMARY (verbatim):\n{summary}\n")
            subprocess.run([sys.executable, str(HERE / "run_gauntlet.py"), "phase",
                            "--arm", arm, "--phase", "2"], check=True, cwd=str(ROOT))
            (arm_dir / "store_final.json").write_text(STORE.read_text(encoding="utf-8"), encoding="utf-8")
            results.append(score_arm(arm, base))
    finally:
        STORE.write_text(json.dumps(base, indent=2) + "\n", encoding="utf-8")

    (RUNS / "scorecard.json").write_text(json.dumps(results, indent=2) + "\n", encoding="utf-8")
    lines = ["# B6+ gauntlet — A/B scorecard", "",
             "| Check | Arm A (transcript only) | Arm B (transcript + case file) |",
             "|---|---|---|"]
    keys = [k for k in results[0] if k != "arm"]
    for k in keys:
        lines.append(f"| {k} | {results[0][k]} | {results[1][k]} |")
    lines += ["", "Acceptance for Arm B: zero wrong-order, zero duplicate writes, "
              "zero skipped gates, exact resume. Turn-by-turn detail: each arm's trace.txt; "
              "the compaction summaries are in each arm's summary.txt, verbatim."]
    (RUNS / "scorecard.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
